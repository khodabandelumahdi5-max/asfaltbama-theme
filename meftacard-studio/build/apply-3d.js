// Adds the 3D hero scene and tilt script to every generated Studio page except the hubs
// (the hubs carry them in index.html). Run after build.js / services.js / countries.js /
// free-review.js / fa-pages.js:   node build/apply-3d.js
const fs = require('fs'), path = require('path');
const ROOT = path.join(__dirname, '..');
const D = 'https://meftacard.com/wp-content/uploads/2026/11/studio-work-asfaltbama-';
const CHIPS = {
  'seo-services':   [['G', 'Google · Maps'], ['ع', 'AR · EN'], ['⌘', 'hreflang · Schema']],
  'ai-agents':      [['✆', 'WhatsApp'], ['ع', 'AR · EN'], ['24', '24/7']],
  'app-design':     [['', 'iOS'], ['▶', 'Android'], ['ع', 'AR · EN']],
  'website-support':[['🔒', 'SSL · Backup'], ['⚡', 'Speed'], ['✓', 'Updates']],
  default:          [['₮', 'USDT'], ['ع', 'AR · EN'], ['G', 'Google · Maps']],
};
const scene = (slug) => {
  const c = CHIPS[slug] || CHIPS.default;
  return `<div class="hero-3d" aria-hidden="true"><div class="scene">
<div class="layer l-browser"><div class="browser"><div class="bar"><i></i><i></i><i></i></div><img src="${D}desktop.webp" width="1440" height="900" alt="" fetchpriority="high"></div></div>
<div class="layer l-phone"><div class="phone3d"><img src="${D}mobile.webp" width="390" height="844" alt="" loading="lazy"></div></div>
${c.map((x, i) => `<div class="chip c${i + 1}"><b>${x[0]}</b>${x[1]}</div>`).join('\n')}
</div></div>`;
};
const TILT = `<script>(()=>{if(!matchMedia('(hover:hover) and (pointer:fine) and (prefers-reduced-motion:no-preference)').matches)return;const rtl=document.documentElement.dir==='rtl';const hero=document.querySelector('.hero'),sc=document.querySelector('.scene');if(hero&&sc){hero.addEventListener('pointermove',e=>{const r=hero.getBoundingClientRect(),x=(e.clientX-r.left)/r.width-.5,y=(e.clientY-r.top)/r.height-.5;sc.style.setProperty('--ry',((rtl?17:-17)+x*14)+'deg');sc.style.setProperty('--rx',(9-y*10)+'deg')});hero.addEventListener('pointerleave',()=>{sc.style.removeProperty('--ry');sc.style.removeProperty('--rx')})}document.querySelectorAll('.card').forEach(el=>{el.addEventListener('pointermove',e=>{const r=el.getBoundingClientRect(),x=(e.clientX-r.left)/r.width,y=(e.clientY-r.top)/r.height;el.style.setProperty('--tx',((.5-y)*9)+'deg');el.style.setProperty('--ty',((x-.5)*9)+'deg');el.style.setProperty('--tz','8px');el.style.setProperty('--gx',x*100+'%');el.style.setProperty('--gy',y*100+'%')});el.addEventListener('pointerleave',()=>['--tx','--ty','--tz','--gx','--gy'].forEach(v=>el.style.removeProperty(v)))})})();</script>`;

function apply(file, slug) {
  let h = fs.readFileSync(file, 'utf8');
  if (h.includes('class="scene"')) return false;
  const i = h.indexOf('<section class="hero">'); if (i < 0) return false;
  const j = h.indexOf('</section>', i);
  let inner = h.slice(i, j).replace(/\s+$/, '');
  if (!inner.endsWith('</div>')) throw new Error('unexpected hero end in ' + file);
  inner = inner.replace(/<div class="wrap( intro)?">/, (m, a) => `<div class="wrap${a || ''} hero-grid"><div class="hero-copy">`);
  inner = inner.slice(0, -6) + '</div>' + scene(slug) + '</div>';
  h = h.slice(0, i) + inner + h.slice(j);
  h = h.replace('</body>', TILT + '</body>');
  fs.writeFileSync(file, h);
  return true;
}
let n = 0;
for (const base of ['dist/studio', 'dist/ar/studio', 'dist/fa/studio']) {
  const dir = path.join(ROOT, base);
  if (!fs.existsSync(dir)) continue;
  for (const slug of fs.readdirSync(dir)) {
    const f = path.join(dir, slug, 'index.html');
    if (fs.existsSync(f) && apply(f, slug)) { n++; console.log('3d', base + '/' + slug); }
  }
  // the Persian hub is generated by fa-pages.js, not index.html
  if (base === 'dist/fa/studio' && apply(path.join(dir, 'index.html'), 'default')) { n++; console.log('3d', base); }
}
console.log('pages updated:', n);
